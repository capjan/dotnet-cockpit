    public static async Task WarmCacheAsync(ToolsSnapshot snapshot, HttpClient httpClient, CancellationToken cancellationToken)
    {
        var allTools = snapshot.Global.Tools.Concat(snapshot.Local.Tools)
            .Select(t => (Id: t.PackageId, Version: t.Version))
            .Concat(FeaturedSheetPackages)
            .GroupBy(t => t.Id, StringComparer.OrdinalIgnoreCase)
            .Select(g => g.First())
            .ToArray();
        if (allTools.Length == 0) return;

        var now = DateTimeOffset.UtcNow;
        var missingIds = allTools
            .Where(t => !NuGetCache.TryGetValue(t.Id, out var cached) || (now - cached.FetchedAt) > TimeSpan.FromMinutes(15))
            .Select(t => t.Id)
            .ToArray();

        if (missingIds.Length > 0)
        {
            try
            {
                using var cts = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
                cts.CancelAfter(TimeSpan.FromSeconds(4));

                var queryTerms = string.Join("+", missingIds.Select(id => $"packageid:{Uri.EscapeDataString(id)}"));
                var url = $"https://azuresearch-usnc.nuget.org/query?q={queryTerms}&prerelease=true&semVerLevel=2.0.0&take=50";
                using var response = await httpClient.GetAsync(url, cts.Token);
                if (response.IsSuccessStatusCode)
                {
                    await using var stream = await response.Content.ReadAsStreamAsync(cts.Token);
                    using var doc = await JsonDocument.ParseAsync(stream, cancellationToken: cts.Token);
                    if (doc.RootElement.TryGetProperty("data", out var dataArr) && dataArr.ValueKind == JsonValueKind.Array)
                    {
                        foreach (var item in dataArr.EnumerateArray())
                        {
                            var id = item.TryGetProperty("id", out var idEl) ? idEl.GetString() : null;
                            if (string.IsNullOrWhiteSpace(id)) continue;

                            var latestVer = item.TryGetProperty("version", out var vEl) ? vEl.GetString() ?? "" : "";
                            var desc = item.TryGetProperty("description", out var dEl) ? dEl.GetString() : null;
                            var projUrl = item.TryGetProperty("projectUrl", out var pEl) ? pEl.GetString() : null;
                            var iconUrl = item.TryGetProperty("iconUrl", out var iEl) ? iEl.GetString() : null;
                            var verified = item.TryGetProperty("verified", out var verEl) && verEl.ValueKind == JsonValueKind.True;
                            var totalDownloads = item.TryGetProperty("totalDownloads", out var dlEl) && dlEl.TryGetInt64(out var dl) ? dl : 0L;

                            string? authors = null;
                            if (item.TryGetProperty("authors", out var authEl))
                            {
                                if (authEl.ValueKind == JsonValueKind.Array)
                                    authors = string.Join(", ", authEl.EnumerateArray().Select(a => a.GetString()).Where(s => !string.IsNullOrWhiteSpace(s)));
                                else if (authEl.ValueKind == JsonValueKind.String)
                                    authors = authEl.GetString();
                            }

                            var tags = Array.Empty<string>();
                            if (item.TryGetProperty("tags", out var tagsEl) && tagsEl.ValueKind == JsonValueKind.Array)
                            {
                                tags = tagsEl.EnumerateArray()
                                    .Select(t => t.GetString() ?? "")
                                    .Where(t => !string.IsNullOrWhiteSpace(t))
                                    .Distinct(StringComparer.OrdinalIgnoreCase)
                                    .Take(6)
                                    .ToArray();
                            }

                            string? latestStable = null;
                            if (item.TryGetProperty("versions", out var versEl) && versEl.ValueKind == JsonValueKind.Array)
                            {
                                var allVers = versEl.EnumerateArray()
                                    .Select(v => v.TryGetProperty("version", out var vv) ? vv.GetString() : null)
                                    .Where(v => !string.IsNullOrWhiteSpace(v))
                                    .Select(v => v!)
                                    .ToArray();
                                latestStable = allVers
                                    .Where(v => !v.Contains('-'))
                                    .OrderByDescending(v => v, SdkDownloadsSection.SdkVersionComparer.Instance)
                                    .FirstOrDefault();
                            }

                            NuGetCache[id] = new CachedNuGetPackage(
                                id,
                                latestVer,
                                latestStable,
                                desc,
                                projUrl,
                                authors,
                                tags,
                                totalDownloads,
                                verified,
                                iconUrl,
                                now);
                        }
                    }
                }
            }
            catch
            {
                // Ignore transient network errors and rely on local .nuspec metadata.
            }
        }

        // Fetch flatcontainer icons for packages that lack an embedded local icon file in .store
        foreach (var tool in allTools)
        {
            if (RemoteIconCache.ContainsKey(tool.Id)) continue;
            if (HasLocalStoreIcon(tool.Id, tool.Version)) continue;
            if (!NuGetCache.TryGetValue(tool.Id, out var pkg) || string.IsNullOrWhiteSpace(pkg.IconUrl))
            {
                RemoteIconCache[tool.Id] = null;
                continue;
            }

            try
            {
                using var iconCts = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
                iconCts.CancelAfter(TimeSpan.FromSeconds(2));
                var lowerId = tool.Id.ToLowerInvariant();
                var targetVer = (!string.IsNullOrWhiteSpace(pkg.LatestStableVersion) ? pkg.LatestStableVersion : tool.Version).ToLowerInvariant();
                var flatIconUrl = $"https://api.nuget.org/v3-flatcontainer/{Uri.EscapeDataString(lowerId)}/{Uri.EscapeDataString(targetVer)}/icon";
                using var iconResp = await httpClient.GetAsync(flatIconUrl, iconCts.Token);
                if (iconResp.IsSuccessStatusCode)
                {
                    var bytes = await iconResp.Content.ReadAsByteArrayAsync(iconCts.Token);
                    var detectedMime = DetectImageMimeType(bytes, iconResp.Content.Headers.ContentType?.MediaType);
                    if (detectedMime is not null)
                    {
                        RemoteIconCache[tool.Id] = $"data:{detectedMime};base64,{Convert.ToBase64String(bytes)}";
                        continue;
                    }
                }
            }
            catch
            {
                // Fall back to standard NuGet logo if flatcontainer icon cannot be fetched.
            }
            RemoteIconCache[tool.Id] = null;
        }

        if (missingIds.Length > 0) Interlocked.Increment(ref generation);
    }

    public static async Task<(byte[]? Bytes, string ContentType)> GetOrFetchIconAsync(string packageId, string version, HttpClient httpClient, CancellationToken cancellationToken)
    {
        var meta = Resolve(packageId, version, false);
        if (!string.IsNullOrEmpty(meta.IconDataUri) && TryDecodeDataUri(meta.IconDataUri, out var cachedBytes, out var cachedMime))
        {
            return (cachedBytes, cachedMime);
        }

        if (!RemoteIconCache.ContainsKey(packageId) && !string.IsNullOrWhiteSpace(packageId) && !string.IsNullOrWhiteSpace(version))
        {
            try
            {
                using var iconCts = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
                iconCts.CancelAfter(TimeSpan.FromSeconds(2));
                var lowerId = packageId.ToLowerInvariant();
                var lowerVer = version.ToLowerInvariant();
                var flatIconUrl = $"https://api.nuget.org/v3-flatcontainer/{Uri.EscapeDataString(lowerId)}/{Uri.EscapeDataString(lowerVer)}/icon";
                using var iconResp = await httpClient.GetAsync(flatIconUrl, iconCts.Token);
                if (iconResp.IsSuccessStatusCode)
                {
                    var bytes = await iconResp.Content.ReadAsByteArrayAsync(iconCts.Token);
                    var detectedMime = DetectImageMimeType(bytes, iconResp.Content.Headers.ContentType?.MediaType);
                    if (detectedMime is not null)
                    {
                        RemoteIconCache[packageId] = $"data:{detectedMime};base64,{Convert.ToBase64String(bytes)}";
                        return (bytes, detectedMime);
                    }
                }
            }
            catch
            {
                // Ignore network failure and return standard NuGet SVG.
            }
            RemoteIconCache[packageId] = null;
        }

        return (System.Text.Encoding.UTF8.GetBytes(NuGetLogoSvg), "image/svg+xml");
    }

    private static string? DetectImageMimeType(byte[] bytes, string? contentType)
    {
        if (bytes.Length is <= 8 or > 200_000) return null;
        if (bytes[0] == 0x89 && bytes[1] == 0x50 && bytes[2] == 0x4E && bytes[3] == 0x47)
            return "image/png";
        if (bytes[0] == 0xFF && bytes[1] == 0xD8 && bytes[2] == 0xFF)
            return "image/jpeg";
        if (bytes.Length >= 12 && bytes[0] == (byte)'R' && bytes[1] == (byte)'I' && bytes[2] == (byte)'F' && bytes[3] == (byte)'F' &&
            bytes[8] == (byte)'W' && bytes[9] == (byte)'E' && bytes[10] == (byte)'B' && bytes[11] == (byte)'P')
            return "image/webp";
        var head = System.Text.Encoding.UTF8.GetString(bytes.AsSpan(0, Math.Min(bytes.Length, 256))).TrimStart();
        if (head.StartsWith("<svg", StringComparison.OrdinalIgnoreCase) ||
            (head.StartsWith("<?xml", StringComparison.OrdinalIgnoreCase) && head.Contains("<svg", StringComparison.OrdinalIgnoreCase)))
            return "image/svg+xml";
        if (!string.IsNullOrWhiteSpace(contentType) && contentType.StartsWith("image/", StringComparison.OrdinalIgnoreCase))
            return contentType;
        return null;
    }

    private static bool TryDecodeDataUri(string dataUri, out byte[] bytes, out string mimeType)
    {
        bytes = [];
        mimeType = "image/png";
        if (!dataUri.StartsWith("data:", StringComparison.OrdinalIgnoreCase)) return false;
        var commaIdx = dataUri.IndexOf(',');
        if (commaIdx < 0) return false;
        var header = dataUri[5..commaIdx];
        var semiIdx = header.IndexOf(';');
        if (semiIdx > 0) mimeType = header[..semiIdx];
        try
        {
            bytes = Convert.FromBase64String(dataUri[(commaIdx + 1)..]);
            return bytes.Length > 0;
        }
        catch
        {
            return false;
        }
    }

    public static ToolMetadata Resolve(string packageId, string version, bool isLocal, string? manifestPath = null)
    {
        KnownTools.TryGetValue(packageId, out var builtIn);
        NuGetCache.TryGetValue(packageId, out var nuget);
        var defaultKind = builtIn?.IconKind ?? InferIconKind(packageId);

        var userProfile = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
        var lowerId = packageId.ToLowerInvariant();
        var lowerVer = version.ToLowerInvariant();

        var storeDir = FindStoreDirectory(userProfile, lowerId, lowerVer);
        var exactStoreDir = Path.Combine(userProfile, ".dotnet", "tools", ".store", lowerId, lowerVer);

        var displayStorePath = !string.IsNullOrWhiteSpace(manifestPath)
            ? manifestPath
            : Directory.Exists(exactStoreDir)
                ? exactStoreDir
                : Path.Combine(userProfile, ".dotnet", "tools");

        string? nuspecDescription = null;
        string? nuspecAuthors = null;
        string? nuspecLicense = null;
        string? nuspecProjectUrl = null;
        string? nuspecRepoUrl = null;
        string[]? nuspecTags = null;
        string? iconDataUri = null;

        if (!string.IsNullOrEmpty(storeDir))
        {
            try
            {
                var nuspecPath = Directory.EnumerateFiles(storeDir, "*.nuspec").FirstOrDefault();
                if (nuspecPath is not null)
                {
                    var doc = XDocument.Load(nuspecPath);
                    var meta = doc.Root?.Elements().FirstOrDefault(e => e.Name.LocalName == "metadata");
                    if (meta is not null)
                    {
                        nuspecDescription = GetElementValue(meta, "description");
                        nuspecAuthors = GetElementValue(meta, "authors");

                        var licenseEl = meta.Elements().FirstOrDefault(e => e.Name.LocalName == "license");
                        if (licenseEl is not null)
                        {
                            var licType = licenseEl.Attribute("type")?.Value;
                            var licVal = licenseEl.Value.Trim();
                            if (string.Equals(licType, "file", StringComparison.OrdinalIgnoreCase) || licVal.Contains('\\') || licVal.Contains('/'))
                                nuspecLicense = "Bundled license";
                            else if (!string.IsNullOrWhiteSpace(licVal))
                                nuspecLicense = licVal;
                        }

                        nuspecProjectUrl = GetElementValue(meta, "projectUrl");
                        var tagsRaw = GetElementValue(meta, "tags");
                        if (!string.IsNullOrWhiteSpace(tagsRaw))
                        {
                            nuspecTags = tagsRaw
                                .Split([' ', ',', ';'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                                .Distinct(StringComparer.OrdinalIgnoreCase)
                                .Take(6)
                                .ToArray();
                        }

                        var repoEl = meta.Elements().FirstOrDefault(e => e.Name.LocalName == "repository");
                        nuspecRepoUrl = repoEl?.Attribute("url")?.Value;

                        var iconRel = GetElementValue(meta, "icon");
                        if (!string.IsNullOrWhiteSpace(iconRel))
                        {
                            iconDataUri = TryReadIconDataUri(storeDir, iconRel);
                        }
                    }
                }
            }
            catch
            {
                // Ignore malformed local cache metadata and fall back cleanly.
            }
        }

        if (string.IsNullOrEmpty(iconDataUri) && RemoteIconCache.TryGetValue(packageId, out var remoteIcon) && !string.IsNullOrEmpty(remoteIcon))
        {
            iconDataUri = remoteIcon;
        }

        var rawDescription = !string.IsNullOrWhiteSpace(nuspecDescription)
            ? nuspecDescription
            : nuget?.Description;

        var fullDescription = NormalizeDescription(rawDescription)
            ?? builtIn?.FullDescription
            ?? (isLocal
                ? $"Local .NET CLI tool package ({packageId}) declared in the workspace tool manifest."
                : $"Global .NET CLI tool package ({packageId}) installed for the current user account.");

        var summary = SummarizeDescription(rawDescription)
            ?? builtIn?.Summary
            ?? FirstSentence(fullDescription);

        var authors = !string.IsNullOrWhiteSpace(nuspecAuthors)
            ? nuspecAuthors
            : !string.IsNullOrWhiteSpace(nuget?.Authors)
                ? nuget.Authors
                : builtIn?.Authors ?? InferAuthor(packageId);

        var license = !string.IsNullOrWhiteSpace(nuspecLicense)
            ? nuspecLicense
            : builtIn?.License ?? "NuGet";

        var repoUrl = !string.IsNullOrWhiteSpace(nuspecRepoUrl)
            ? nuspecRepoUrl
            : builtIn?.ProjectUrl ?? "";

        var projectUrl = !string.IsNullOrWhiteSpace(nuspecProjectUrl)
            ? nuspecProjectUrl
            : !string.IsNullOrWhiteSpace(nuget?.ProjectUrl)
                ? nuget.ProjectUrl
                : !string.IsNullOrWhiteSpace(repoUrl)
                    ? repoUrl
                    : $"https://www.nuget.org/packages/{packageId}";

        var tags = nuspecTags is { Length: > 0 }
            ? nuspecTags
            : nuget?.Tags is { Length: > 0 }
                ? nuget.Tags
                : builtIn?.Tags ?? ["dotnet-tool", "cli"];

        // Authoritative Verified check: from NuGet.org API when available, otherwise only explicitly verified built-ins.
        var isVerified = nuget is not null
            ? nuget.Verified
            : builtIn?.IsVerified == true;

        var totalDownloads = nuget?.TotalDownloads ?? builtIn?.FallbackDownloads;
        var downloadsDisplay = totalDownloads is > 0 ? FormatCompactDownloads(totalDownloads.Value) : "";
        var downloadsFullDisplay = totalDownloads is > 0 ? FormatFullDownloads(totalDownloads.Value) : "Published on NuGet.org";

        var isInstalledPreview = version.Contains('-', StringComparison.Ordinal);
        var candidateLatest = isInstalledPreview
            ? (nuget?.LatestVersion ?? nuget?.LatestStableVersion)
            : (nuget?.LatestStableVersion ?? nuget?.LatestVersion);
        var hasUpdate = !string.IsNullOrWhiteSpace(candidateLatest) &&
            !string.Equals(candidateLatest, version, StringComparison.OrdinalIgnoreCase) &&
            SdkDownloadsSection.SdkVersionComparer.Instance.Compare(candidateLatest, version) > 0;

        return new ToolMetadata(
            packageId,
            summary,
            fullDescription,
            authors,
            license,
            projectUrl,
            repoUrl,
            tags,
            iconDataUri,
            defaultKind,
            displayStorePath,
            isVerified,
            downloadsDisplay,
            downloadsFullDisplay,
            hasUpdate ? candidateLatest : null,
            hasUpdate);
    }

    public static string FormatCompactDownloads(long count)
    {
        if (count >= 1_000_000_000)
            return $"{(count / 1_000_000_000.0).ToString("0.#", CultureInfo.InvariantCulture)}B";
        if (count >= 1_000_000)
            return $"{(count / 1_000_000.0).ToString("0.#", CultureInfo.InvariantCulture)}M";
        if (count >= 10_000)
            return $"{(count / 1_000.0).ToString("0.#", CultureInfo.InvariantCulture)}K";
        return count.ToString("N0", CultureInfo.InvariantCulture);
    }

    public static string FormatFullDownloads(long count) =>
        count >= 10_000
            ? $"{count.ToString("N0", CultureInfo.InvariantCulture)} ({FormatCompactDownloads(count)})"
            : $"{count.ToString("N0", CultureInfo.InvariantCulture)} total";


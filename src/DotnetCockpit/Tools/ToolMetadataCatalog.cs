    public static string InferIconKind(string packageId)
    {
        var id = packageId.ToLowerInvariant();
        if (id.Contains("ef") || id.Contains("sql") || id.Contains("db") || id.Contains("data")) return "database";
        if (id.Contains("cover") || id.Contains("test") || id.Contains("sec") || id.Contains("audit")) return "shield";
        if (id.Contains("report") || id.Contains("bench") || id.Contains("metric")) return "chart";
        if (id.Contains("ip") || id.Contains("http") || id.Contains("web") || id.Contains("net") && !id.StartsWith("dotnet")) return "globe";
        if (id.Contains("md") || id.Contains("markdown") || id.Contains("doc")) return "markdown";
        if (id.Contains("regex") || id.Contains("grep") || id.Contains("search")) return "regex";
        if (id.Contains("wake") || id.Contains("power") || id.Contains("bolt")) return "bolt";
        if (id.Contains("doctor") || id.Contains("diag") || id.Contains("health")) return "doctor";
        if (id.Contains("format") || id.Contains("csharpier") || id.Contains("lint") || id.Contains("fantomas")) return "sparkles";
        if (id.Contains("trace") || id.Contains("dump") || id.Contains("counter") || id.Contains("monitor")) return "activity";
        if (id.Contains("outdated") || id.Contains("nuget") || id.Contains("pack")) return "package";
        return "terminal";
    }

    private static bool HasLocalStoreIcon(string packageId, string version)
    {
        try
        {
            var userProfile = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
            var lowerId = packageId.ToLowerInvariant();
            var lowerVer = version.ToLowerInvariant();
            var globalStoreDir = Path.Combine(userProfile, ".dotnet", "tools", ".store", lowerId, lowerVer, lowerId, lowerVer);
            if (!Directory.Exists(globalStoreDir)) return false;
            var nuspecPath = Directory.EnumerateFiles(globalStoreDir, "*.nuspec").FirstOrDefault();
            if (nuspecPath is null) return false;
            var doc = XDocument.Load(nuspecPath);
            var meta = doc.Root?.Elements().FirstOrDefault(e => e.Name.LocalName == "metadata");
            var iconRel = meta is not null ? GetElementValue(meta, "icon") : null;
            return !string.IsNullOrWhiteSpace(iconRel);
        }
        catch
        {
            return false;
        }
    }

    private static string InferAuthor(string packageId)
    {
        if (packageId.StartsWith("dotnet-", StringComparison.OrdinalIgnoreCase) ||
            packageId.StartsWith("Microsoft.", StringComparison.OrdinalIgnoreCase))
            return "Microsoft";
        var parts = packageId.Split(['.', '-'], StringSplitOptions.RemoveEmptyEntries);
        return parts.Length > 0 ? parts[0] : "NuGet author";
    }

    private static string? GetElementValue(XElement parent, string localName) =>
        parent.Elements().FirstOrDefault(e => e.Name.LocalName == localName)?.Value?.Trim();

    private static string? TryReadIconDataUri(string storeDir, string iconRelativePath)
    {
        var normalizedRel = iconRelativePath.Replace('\\', Path.DirectorySeparatorChar).Replace('/', Path.DirectorySeparatorChar);
        var fullDir = Path.GetFullPath(storeDir);
        var fullIcon = Path.GetFullPath(Path.Combine(fullDir, normalizedRel));
        if (!fullIcon.StartsWith(fullDir, StringComparison.Ordinal) || !File.Exists(fullIcon))
            return null;

        var info = new FileInfo(fullIcon);
        if (info.Length is <= 0 or > 200_000)
            return null;

        var ext = Path.GetExtension(fullIcon).ToLowerInvariant();
        var mime = ext switch
        {
            ".png" => "image/png",
            ".jpg" or ".jpeg" => "image/jpeg",
            ".svg" => "image/svg+xml",
            ".webp" => "image/webp",
            _ => null
        };
        if (mime is null) return null;

        var bytes = File.ReadAllBytes(fullIcon);
        return $"data:{mime};base64,{Convert.ToBase64String(bytes)}";
    }

    private static string? NormalizeDescription(string? raw)
    {
        if (string.IsNullOrWhiteSpace(raw)) return null;
        var lines = raw.Split(['\r', '\n'], StringSplitOptions.TrimEntries)
            .Where(l => l.Length > 0)
            .ToArray();
        return lines.Length == 0 ? null : string.Join("\n", lines);
    }

    private static string? SummarizeDescription(string? raw)
    {
        if (string.IsNullOrWhiteSpace(raw)) return null;
        var firstLine = raw.Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .FirstOrDefault();
        if (string.IsNullOrWhiteSpace(firstLine)) return null;
        return firstLine.Length <= 115 ? firstLine : firstLine[..112].TrimEnd() + "…";
    }

    private static string FirstSentence(string text)
    {
        var firstLine = text.Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .FirstOrDefault() ?? text;
        return firstLine.Length <= 115 ? firstLine : firstLine[..112].TrimEnd() + "…";
    }
